fn put_u64(out: &mut [u8], offset: usize, value: u64) {
    out[offset..offset + 8].copy_from_slice(&value.to_le_bytes());
}

fn put_u32(out: &mut [u8], offset: usize, value: u32) {
    out[offset..offset + 4].copy_from_slice(&value.to_le_bytes());
}

/// Canonical executable bytes with an authenticated entrypoint and limits.
pub fn emulator_component() -> [u8; EMULATOR_COMPONENT_LEN] {
    let mut out = [0u8; EMULATOR_COMPONENT_LEN];
    out[..10].copy_from_slice(b"ASTRIDCOMP");
    out[10] = 1;
    put_u64(&mut out, 16, 0);
    put_u64(&mut out, 24, EMULATOR_COMPONENT_HEADER_LEN as u64);
    put_u32(&mut out, 32, EMULATOR_COMPONENT_CODE_LEN as u32);
    put_u32(&mut out, 36, 1);
    put_u32(&mut out, 40, 16);
    put_u32(&mut out, 44, 4);
    out[EMULATOR_COMPONENT_HEADER_LEN..].copy_from_slice(&MACHINE_CODE);
    out
}

pub fn emulator_component_id() -> ContentId {
    ContentId::from_payload(&emulator_component())
}

pub fn emulator_components() -> ComponentSet {
    match ComponentSet::try_from_slice(&[emulator_component_id()]) {
        Ok(components) => components,
        Err(_) => panic!("the emulator fixture contains one valid component identity"),
    }
}

#[cfg(test)]
mod readiness_route_tests {
    use super::*;

    #[test]
    fn running_stop_trap_is_exclusive_and_all_other_routes_stay_on_base_paths() {
        let component = emulator_component();
        let code = &component[EMULATOR_COMPONENT_HEADER_LEN..];
        let rel8 = |offset: usize| i8::from_le_bytes([code[offset + 1]]);
        let rel32 =
            |offset: usize| i32::from_le_bytes(code[offset + 1..offset + 5].try_into().unwrap());

        // All explicit scenario compares and branch targets stay frozen. The
        // fall-through scenarios (4, 10, and 11) enter the replaced shared
        // pause gate at offset 25.
        assert_eq!(
            &code[..25],
            &[
                0x83, 0xff, 0x05, 0x74, 0x40, 0x83, 0xff, 0x00, 0x74, 0x1f, 0x83, 0xff, 0x01, 0x74,
                0x10, 0x83, 0xff, 0x02, 0x74, 0x05, 0x83, 0xff, 0x03, 0x74, 0x12,
            ]
        );
        assert_eq!((3, 5 + i32::from(rel8(3))), (3, 69));
        assert_eq!((8, 10 + i32::from(rel8(8))), (8, 41));
        assert_eq!((13, 15 + i32::from(rel8(13))), (13, 31));
        assert_eq!((18, 20 + i32::from(rel8(18))), (18, 25));
        assert_eq!((23, 25 + i32::from(rel8(23))), (23, 43));

        assert_eq!(&code[25..31], &[0xe9, 0x74, 0x01, 0x00, 0x00, 0x0b]);
        assert_eq!(code[31], 0x31);
        assert_eq!(30 + rel32(25), 402);

        // A foreign selector input branches directly to the stable pause
        // loop. RunningStop takes the branch and executes exactly one trap;
        // iretq lands on the same loop, never on the selector or padding.
        assert_eq!(
            &code[402..415],
            &[
                0x83, 0xff, 0x0b, 0x75, 0x02, 0xcd, 0x40, 0xf3, 0x90, 0xeb, 0xfc, 0x00, 0x00,
            ]
        );
        assert_eq!(code[402..405], [0x83, 0xff, 0x0b]);
        assert_eq!(407 + i32::from(rel8(405)), 409);
        assert_eq!(&code[407..409], &[0xcd, 0x40]);
        assert_eq!(&code[409..412], &[0xf3, 0x90, 0xeb]);
        assert_eq!(413 + i32::from(rel8(411)), 409);
        assert_eq!(&code[413..415], &[0x00, 0x00]);

        assert_eq!(&code[69..71], &[0x0f, 0x0b]);
        assert_eq!(
            &code[71..86],
            &[
                0x83, 0xff, 0x06, 0x74, 0x15, 0x83, 0xff, 0x09, 0x74, 0x10, 0x83, 0xff, 0x07, 0x74,
                0x48,
            ]
        );
        assert_eq!(76 + i32::from(rel8(74)), 97);
        assert_eq!(81 + i32::from(rel8(79)), 97);
        assert_eq!(86 + i32::from(rel8(84)), 158);
        assert_eq!(
            &code[86..95],
            &[0x83, 0xff, 0x08, 0x0f, 0x84, 0x15, 0x01, 0x00, 0x00]
        );
        assert_eq!(95 + rel32(90), 372);
        assert_eq!(&code[95..97], &[0x0f, 0x0b]);
        assert_eq!(u64::from_le_bytes(component[16..24].try_into().unwrap()), 0);
        assert_eq!(
            u64::from_le_bytes(component[24..32].try_into().unwrap()),
            EMULATOR_COMPONENT_HEADER_LEN as u64
        );
        assert_eq!(
            u32::from_le_bytes(component[32..36].try_into().unwrap()),
            EMULATOR_COMPONENT_CODE_LEN as u32
        );
        assert_eq!(u32::from_le_bytes(component[36..40].try_into().unwrap()), 1);
        assert_eq!(
            u32::from_le_bytes(component[40..44].try_into().unwrap()),
            16
        );
        assert_eq!(u32::from_le_bytes(component[44..48].try_into().unwrap()), 4);
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn canonical_fixture_binds_code_entrypoint_and_limits() {
        let component = emulator_component();
        assert_eq!(component.len(), EMULATOR_COMPONENT_LEN);
        assert_eq!(&component[..10], b"ASTRIDCOMP");
        assert_eq!(component[10], 1);
        assert!(component[11..16].iter().all(|byte| *byte == 0));

        let entrypoint = u64::from_le_bytes(component[16..24].try_into().unwrap());
        let code_offset = u64::from_le_bytes(component[24..32].try_into().unwrap());
        let code_len = u32::from_le_bytes(component[32..36].try_into().unwrap());
        let stack_pages = u32::from_le_bytes(component[36..40].try_into().unwrap());
        let max_frames = u32::from_le_bytes(component[40..44].try_into().unwrap());
        let quota_ticks = u32::from_le_bytes(component[44..48].try_into().unwrap());

        assert_eq!(entrypoint, 0);
        assert_eq!(code_offset, EMULATOR_COMPONENT_HEADER_LEN as u64);
        assert_eq!(code_len as usize, EMULATOR_COMPONENT_CODE_LEN);
        assert_eq!(stack_pages, 1);
        assert_eq!(max_frames, 16);
        assert_eq!(quota_ticks, 4);
        assert_eq!(
            component[EMULATOR_COMPONENT_HEADER_LEN..].len(),
            EMULATOR_COMPONENT_CODE_LEN
        );
        assert!(
            component[EMULATOR_COMPONENT_HEADER_LEN..]
                .iter()
                .any(|byte| *byte != 0)
        );
    }

    #[test]
    fn fixture_component_set_contains_exact_canonical_identity() {
        let components = emulator_components();
        assert_eq!(components.count(), 1);
        assert_eq!(components.digest(0), Some(emulator_component_id()));
        assert_eq!(components.digest(1), None);
        assert_eq!(emulator_component(), emulator_component());
    }
}
